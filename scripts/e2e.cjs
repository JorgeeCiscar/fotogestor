const { _electron } = require('playwright')
const path = require('node:path'), fs = require('node:fs'), os = require('node:os'), { execFileSync } = require('node:child_process')
const ROOT = path.resolve(__dirname, '..')
const S = fs.mkdtempSync(path.join(os.tmpdir(), 'fotogestor-e2e-'))
for (const d of ['imgs', 'data', 'shots']) fs.mkdirSync(path.join(S, d))
execFileSync('node', [path.join(__dirname, 'make-test-images.cjs'), path.join(S, 'imgs')])
console.log('directorio de prueba:', S)
;(async () => {
  const app = await _electron.launch({ executablePath: require('electron'),
    args: [ROOT, '--no-sandbox'], env: { ...process.env, FOTOGESTOR_DATA_DIR: S + '/data' } })
  const errors = []
  const win = await app.firstWindow()
  win.on('pageerror', (e) => errors.push(e.message))
  win.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  await win.setViewportSize({ width: 1400, height: 900 })
  await app.evaluate(({ dialog }, dir) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [dir] }) }, S + '/imgs')
  win.on('dialog', (d) => d.accept())

  // Cliente
  await win.click('text=Clientes'); await win.click('text=+ Nuevo cliente')
  await win.fill('.modal label:has-text("Nombre") input', 'Ana García')
  await win.fill('.modal input[type=email]', 'ana@example.com')
  await win.click('.modal button:has-text("Guardar")')
  await win.waitForSelector('td:has-text("Ana García")')
  // Sesión
  await win.click('nav >> text=Sesiones'); await win.click('text=+ Nueva sesión')
  await win.fill('.modal label:has-text("Título") input', 'Boda Ana y Luis')
  await win.selectOption('.modal label:has-text("Cliente") select', { label: 'Ana García' })
  await win.selectOption('.modal label:has-text("Tipo") select', 'Boda')
  await win.fill('.modal input[type=date]', '2026-12-12')
  await win.selectOption('.modal label:has-text("Estado") select', 'editando')
  await win.fill('.modal input[type=number]', '1800')
  await win.click('.modal button:has-text("Guardar")')
  await win.waitForSelector('.dropzone')
  // Importar
  await win.click('.dropzone button')
  await win.waitForFunction(() => document.querySelectorAll('.thumb img').length === 8, null, { timeout: 30000 })
  await win.waitForTimeout(500)
  console.log('toast:', await win.textContent('.toast'))
  // Re-importar → duplicados
  await win.click('button:has-text("+ Importar fotos")'); await win.waitForTimeout(1500)
  console.log('toast 2:', await win.textContent('.toast'))
  // Culling por teclado
  await win.keyboard.press('p'); await win.keyboard.press('5'); await win.keyboard.press('ArrowRight')
  await win.keyboard.press('x'); await win.keyboard.press('ArrowRight')
  await win.keyboard.press('p'); await win.keyboard.press('3'); await win.keyboard.press('ArrowRight'); await win.keyboard.press('ArrowRight')
  await win.keyboard.press('p'); await win.keyboard.press('4')
  await win.waitForTimeout(400)
  await win.screenshot({ path: S + '/shots/sesion.png' })
  await win.keyboard.press('Enter'); await win.waitForTimeout(600)
  await win.screenshot({ path: S + '/shots/visor.png' })
  console.log('viewer:', (await win.textContent('.viewer-info dl')).replace(/\s+/g,' '))
  await win.keyboard.press('Escape')
  await win.click('.segmented button:has-text("Elegidas")'); await win.waitForTimeout(300)
  console.log('elegidas visibles:', await win.locator('.thumb').count())
  // Export
  await app.evaluate(({ dialog }, dir) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [dir] }) }, S + '/export')
  await win.click('button:has-text("Exportar elegidas")'); await win.waitForTimeout(800)
  console.log('toast 3:', await win.textContent('.toast'))
  // Persistencia: navegar y volver
  await win.click('nav >> text=Panel'); await win.waitForTimeout(500)
  await win.screenshot({ path: S + '/shots/panel.png' })
  await win.click('nav >> text=Sesiones'); await win.waitForTimeout(500)
  await win.screenshot({ path: S + '/shots/sesiones.png' })
  console.log('errores:', errors)
  await app.close()
  if (!process.env.KEEP_E2E) fs.rmSync(S, { recursive: true, force: true })
  else console.log('capturas en', path.join(S, 'shots'))
})().catch((e) => { console.error(e); process.exit(1) })
